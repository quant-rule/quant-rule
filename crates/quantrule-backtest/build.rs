//! Generate the strategy registry table from the repository registry.
//!
//! The strategy engines need one source of truth for the registered event
//! identities and roles. The registry JSON is the human-owned artifact; this
//! build step turns it into a static table so the engine does not read a file at
//! runtime and cannot silently accept an unregistered identity.
//!
//! The workspace is the product, so the build reads the checked-in registry.
//! A missing or malformed registry fails the build rather than producing an
//! empty table.

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::PathBuf;

fn merge_role(left: &'static str, right: &'static str) -> &'static str {
    if left == "Diagnostic" || right == "Diagnostic" {
        "Diagnostic"
    } else if left == "Signal" || right == "Signal" {
        "Signal"
    } else {
        "Context"
    }
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let registry = manifest.join("../../docs/registry/indicators.json");
    println!("cargo:rerun-if-changed={}", registry.display());
    println!("cargo:rerun-if-changed=build.rs");

    let text = fs::read_to_string(&registry).unwrap_or_else(|error| {
        panic!(
            "cannot read the strategy registry {}: {error}",
            registry.display()
        )
    });
    let value: serde_json::Value =
        serde_json::from_str(&text).expect("the strategy registry is valid JSON");
    let events = value
        .get("events")
        .and_then(serde_json::Value::as_array)
        .expect("the strategy registry has an events array");

    let mut identities: BTreeMap<(u8, u8, u16), &'static str> = BTreeMap::new();
    for event in events {
        if event.get("status").and_then(serde_json::Value::as_str) != Some("active") {
            continue;
        }
        let event_type = event
            .get("event_type")
            .and_then(serde_json::Value::as_u64)
            .expect("an event has an event_type");
        let subtype = event
            .get("subtype")
            .and_then(serde_json::Value::as_u64)
            .expect("an event has a subtype");
        let source = event
            .get("source")
            .and_then(serde_json::Value::as_u64)
            .expect("an event has a source");
        let role = match event
            .get("role")
            .and_then(serde_json::Value::as_str)
            .expect("an event has a role")
        {
            "signal" => "Signal",
            "context" => "Context",
            "diagnostic" => "Diagnostic",
            other => panic!("unknown event role {other:?}"),
        };
        let key = (
            u8::try_from(event_type).expect("the event type fits u8"),
            u8::try_from(subtype).expect("the subtype fits u8"),
            u16::try_from(source).expect("the source fits u16"),
        );
        identities
            .entry(key)
            .and_modify(|existing| *existing = merge_role(existing, role))
            .or_insert(role);
    }
    assert_eq!(
        identities.get(&(3, 8, 5)),
        Some(&"Signal"),
        "the registry must contain the compression-range event as a signal"
    );

    let mut generated = String::from(
        "// @generated by build.rs from docs/registry/indicators.json\n\
         pub(crate) const EVENTS: &[(u8, u8, u16, EventRole)] = &[\n",
    );
    for ((event_type, subtype, source), role) in identities {
        generated.push_str(&format!(
            "    ({event_type}, {subtype}, {source}, EventRole::{role}),\n"
        ));
    }
    generated.push_str("];\n");

    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("strategy_registry.rs");
    fs::write(&out, generated).unwrap_or_else(|error| {
        panic!("cannot write {}: {error}", out.display());
    });
}
