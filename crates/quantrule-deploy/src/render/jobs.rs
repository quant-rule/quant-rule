//! The one-shot database jobs the bootstrap script runs.
//!
//! `db-bootstrap.sh` applies the schema and grant bootstrap with each service's
//! **owner** URL. The cluster, the four logical databases, and the eight roles
//! are PLAT-003's bootstrap; this job converges the schemas and grants in the
//! four databases in order. `migrate.sh` runs the pinned application image once
//! per owner with `--migrate-only`, in the same order. Neither script carries a
//! secret value: the owner URL is a file and the CA is a public config.

use crate::descriptor::v3::Descriptor;

use super::{app_image, pinned, shell_quote};

/// The four owner migrations, in dependency order.
const MIGRATIONS: [(&str, &str); 4] = [
    ("gateway", "qr-gateway"),
    ("data", "qr-data"),
    ("evidence", "qr-evidence"),
    ("simulation", "qr-simulation"),
];

/// Render `jobs/db-bootstrap.sh`.
#[must_use]
pub fn db_bootstrap(descriptor: &Descriptor) -> String {
    let overlay = shell_quote(&descriptor.network.overlay);
    let image = shell_quote(&pinned(&descriptor.images["postgres"]));
    let mut blocks = String::new();
    for (service, sql) in [
        ("gateway", GATEWAY_SQL),
        ("data", CATALOG_SQL),
        ("evidence", EVIDENCE_SQL),
        ("simulation", SIMULATION_SQL),
    ] {
        blocks.push_str(&format!(
            r#"
run_with_sql {service} <<'SQL'
{sql}
SQL
"#
        ));
    }
    format!(
        r#"#!/bin/sh
# Generated by qr-deploy.
#
# PLAT-003 creates the Patroni cluster, the four databases, and the eight
# roles. This job applies each database's schema and grants through that
# service's owner URL, in the fixed order gateway, data, evidence, simulation.
# The URL stays in a file; it is never printed or passed as an argument.
set -eu
OVERLAY={overlay}
IMAGE={image}
CA=pki/database-ca.crt

fail() {{
    printf 'qr-deploy db-bootstrap: %s\n' "$*" >&2
    exit 1
}}

[ -f "$CA" ] || fail "missing $CA"

# psql reads the SQL from stdin; the owner URL is the only credential.
run_with_sql() {{
    service=$1
    file="secrets/${{service}}_owner_database_url"
    [ -f "$file" ] || fail "missing $file"
    {{
        printf '\\connect %s\n' "$(cat "$file")"
        cat
    }} | docker run --rm -i --network "$OVERLAY" \
        -e PGSSLMODE=verify-full \
        -e PGSSLROOTCERT=/run/pki/database-ca.crt \
        -v "$PWD/$CA:/run/pki/database-ca.crt:ro" \
        "$IMAGE" psql -v ON_ERROR_STOP=1 -f -
}}
{blocks}
printf 'databases ready: qr_gateway, qr_catalog, qr_evidence, qr_simulation\n'
"#
    )
}

/// Render `jobs/migrate.sh`.
#[must_use]
pub fn migrate(descriptor: &Descriptor) -> String {
    let overlay = shell_quote(&descriptor.network.overlay);
    let image = shell_quote(&app_image(descriptor));
    let mut runs = String::new();
    for (service, binary) in MIGRATIONS {
        runs.push_str(&format!(
            r#"
docker run --rm --network "$OVERLAY" \
    -e QR_MIGRATE=0 \
    -e QR_DATABASE_OWNER_URL_FILE=/run/secrets/{service}_owner_database_url \
    -e QR_DATABASE_TLS_CA_PATH=/run/pki/database-ca.crt \
    -e PGSSLMODE=verify-full \
    -e PGSSLROOTCERT=/run/pki/database-ca.crt \
    -v "$PWD/secrets/{service}_owner_database_url:/run/secrets/{service}_owner_database_url:ro" \
    -v "$PWD/pki/database-ca.crt:/run/pki/database-ca.crt:ro" \
    "$IMAGE" {binary} --migrate-only
"#
        ));
    }
    format!(
        r#"#!/bin/sh
# Generated by qr-deploy.
#
# Four owner migrations, in dependency order. The application image runs one
# binary with --migrate-only; the owner URL is a mode-600 file and the CA is a
# public bundle. No app URL and no superuser URL is present.
set -eu
OVERLAY={overlay}
IMAGE={image}
{runs}
printf 'migrations complete: gateway, data, evidence, simulation\n'
"#
    )
}

const GATEWAY_SQL: &str = r#"
REVOKE ALL ON DATABASE qr_gateway FROM PUBLIC;
REVOKE TEMP ON DATABASE qr_gateway FROM PUBLIC;
GRANT CONNECT, CREATE ON DATABASE qr_gateway TO qr_gateway_owner;
GRANT CONNECT ON DATABASE qr_gateway TO qr_gateway_app;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO qr_gateway_owner;
GRANT USAGE ON SCHEMA public TO qr_gateway_app;
CREATE SCHEMA IF NOT EXISTS gateway AUTHORIZATION qr_gateway_owner;
REVOKE ALL ON SCHEMA gateway FROM PUBLIC;
GRANT USAGE ON SCHEMA gateway TO qr_gateway_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA gateway TO qr_gateway_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA gateway TO qr_gateway_app;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA gateway TO qr_gateway_app;
ALTER DEFAULT PRIVILEGES FOR ROLE qr_gateway_owner IN SCHEMA gateway
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO qr_gateway_app;
ALTER DEFAULT PRIVILEGES FOR ROLE qr_gateway_owner IN SCHEMA gateway
    GRANT USAGE, SELECT ON SEQUENCES TO qr_gateway_app;
ALTER DEFAULT PRIVILEGES FOR ROLE qr_gateway_owner IN SCHEMA gateway
    GRANT EXECUTE ON FUNCTIONS TO qr_gateway_app;
"#;

