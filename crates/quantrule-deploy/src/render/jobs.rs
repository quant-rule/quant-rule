#[cfg(test)]
mod tests {
    use super::*;

    fn descriptor() -> Descriptor {
        serde_json::from_str(include_str!("../../../../deploy/v3/deploy.example.json"))
            .expect("v3 example")
    }

    #[test]
    fn migrations_are_ordered_and_use_only_the_owner_url() {
        let text = migrate(&descriptor());
        let gateway = text.find("qr-gateway --migrate-only").expect("gateway");
        let data = text.find("qr-data --migrate-only").expect("data");
        let evidence = text.find("qr-evidence --migrate-only").expect("evidence");
        let simulation = text
            .find("qr-simulation --migrate-only")
            .expect("simulation");
        assert!(gateway < data && data < evidence && evidence < simulation);
        assert!(text.contains("QR_DATABASE_OWNER_URL_FILE"));
        assert!(!text.contains("QR_DATABASE_URL_FILE"));
        assert!(!text.contains("QR_DATABASE_URL="));
        assert!(text.contains("PGSSLMODE=verify-full"));
        assert!(text.contains("PGSSLROOTCERT"));
    }

    #[test]
    fn the_bootstrap_script_names_the_four_databases_and_no_value() {
        let text = db_bootstrap(&descriptor());
        for database in ["qr_gateway", "qr_catalog", "qr_evidence", "qr_simulation"] {
            assert!(text.contains(database), "{database}: {text}");
        }
        assert!(!text.contains("postgres://"));
        assert!(!text.contains("amqps://"));
    }

    #[test]
    fn the_stack_name_is_used_in_the_operator_output() {
        let mut value: serde_json::Value =
            serde_json::from_str(include_str!("../../../../deploy/v3/deploy.example.json"))
                .expect("example");
        value["name"] = serde_json::json!("quantrule-lab");
        let descriptor: Descriptor = serde_json::from_value(value).expect("descriptor");
        assert_eq!(super::super::stack_name(&descriptor), "quantrule-lab");
    }
}
