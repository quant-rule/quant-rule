//! The one-shot database jobs the bootstrap script runs.
//!
//! `cluster-bootstrap.sh` creates the four logical databases and eight roles
//! through the superuser password file and the `postgres`/HAProxy endpoint. It
//! reuses the Compose bootstrap's role/database SQL with file-backed passwords.
//! `db-bootstrap.sh` then applies each database's schema and grants through the
//! service's **owner** URL. `migrate.sh` runs the pinned application image once
//! per owner with `--migrate-only`, in the same order. None of the three scripts
//! carries a secret value: the URLs and the superuser password are files, and
//! the CA is a public config.

use crate::descriptor::v3::Descriptor;

use super::{app_image, pinned, shell_quote};

/// The four owner migrations, in dependency order.
const MIGRATIONS: [(&str, &str); 4] = [
    ("gateway", "qr-gateway"),
    ("data", "qr-data"),
    ("evidence", "qr-evidence"),
    ("simulation", "qr-simulation"),
];

/// The eight role URLs, in cluster-bootstrap order.
const ROLE_URLS: [(&str, &str); 8] = [
    ("gateway", "gateway_owner_database_url"),
    ("gateway", "gateway_database_url"),
    ("catalog", "data_owner_database_url"),
    ("catalog", "data_database_url"),
    ("evidence", "evidence_owner_database_url"),
    ("evidence", "evidence_database_url"),
    ("simulation", "simulation_owner_database_url"),
    ("simulation", "simulation_database_url"),
];

/// Render `jobs/cluster-bootstrap.sh`.
#[must_use]
pub fn cluster_bootstrap(descriptor: &Descriptor) -> String {
    let overlay = shell_quote(&descriptor.network.overlay);
    let image = shell_quote(&pinned(&descriptor.images["postgres"]));
    let mut mounts = String::new();
    let mut files = String::from("postgres_superuser_password");
    for (_, name) in ROLE_URLS {
        mounts.push_str(&format!(
            "    -v \"$PWD/secrets/{name}:/run/secrets/{name}:ro\" \\\n"
        ));
        files.push(' ');
        files.push_str(name);
    }
    format!(
        r#"#!/bin/sh
# Generated by qr-deploy.
#
# PLAT-003 creates the Patroni cluster; this job creates the four logical
# databases and eight roles before db-bootstrap.sh and migrate.sh. It connects
# as the superuser through the `postgres`/HAProxy endpoint. The superuser
# password is a mode-600 file; the eight role passwords are read from the owner
# and app URL files inside the container, never from an argument or a log.
set -eu
OVERLAY={overlay}
IMAGE={image}
CA=pki/database-ca.crt

fail() {{
    printf 'qr-deploy cluster-bootstrap: %s\n' "$*" >&2
    exit 1
}}

[ -f "$CA" ] || fail "missing $CA"
for name in {files}; do
    [ -f "secrets/$name" ] || fail "missing secrets/$name"
done

docker run --rm -i --network "$OVERLAY" \
    -e PGHOST=postgres \
    -e PGPORT=5432 \
    -e PGUSER=postgres \
    -e PGDATABASE=postgres \
    -e PGSSLMODE=verify-full \
    -e PGSSLROOTCERT=/run/pki/database-ca.crt \
    -e QR_SUPERUSER_PASSWORD_FILE=/run/secrets/postgres_superuser_password \
    -e PGPASSFILE=/tmp/pgpass \
    -v "$PWD/$CA:/run/pki/database-ca.crt:ro" \
    -v "$PWD/secrets/postgres_superuser_password:/run/secrets/postgres_superuser_password:ro" \
{mounts}    "$IMAGE" sh -eu -c '
        printf "postgres:5432:*:postgres:%s\n" "$(cat "$QR_SUPERUSER_PASSWORD_FILE")" > "$PGPASSFILE"
        chmod 600 "$PGPASSFILE"
        exec psql -v ON_ERROR_STOP=1 -q -f -
    ' <<'SQL'
{sql}
SQL
"#,
        overlay = overlay,
        image = image,
        files = files,
        mounts = mounts,
        sql = CLUSTER_SQL,
    )
}

