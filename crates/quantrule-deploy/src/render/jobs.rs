#[cfg(test)]
mod tests {
    use super::*;

    fn descriptor() -> Descriptor {
        serde_json::from_str(include_str!("../../../../deploy/v3/deploy.example.json"))
            .expect("v3 example")
    }

    #[test]
    fn cluster_bootstrap_creates_the_four_databases_and_eight_roles() {
        let text = cluster_bootstrap(&descriptor());
        for name in [
            "qr_gateway",
            "qr_catalog",
            "qr_evidence",
            "qr_simulation",
            "qr_gateway_owner",
            "qr_gateway_app",
            "qr_catalog_owner",
            "qr_catalog_app",
            "qr_evidence_owner",
            "qr_evidence_app",
            "qr_simulation_owner",
            "qr_simulation_app",
        ] {
            assert!(text.contains(name), "{name}: {text}");
        }
        assert!(text.contains("CREATE ROLE"), "{text}");
        assert!(text.contains("CREATE DATABASE"), "{text}");
        assert!(text.contains("ALTER DATABASE"), "{text}");
        assert!(text.contains("PGPASSFILE"), "{text}");
        assert!(
            text.contains("/run/secrets/gateway_owner_database_url"),
            "{text}"
        );
        assert!(text.contains("/run/secrets/data_database_url"), "{text}");
        assert!(!text.contains("postgres://"), "{text}");
        assert!(!text.contains("amqps://"), "{text}");
        let secret = std::fs::read_to_string(
            std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("../../deploy/v3/secrets/postgres_superuser_password"),
        )
        .expect("superuser fixture");
        assert!(
            !text.contains(secret.trim()),
            "the cluster job embedded a password"
        );
    }

    #[test]
    fn cluster_bootstrap_mounts_all_eight_role_urls() {
        let text = cluster_bootstrap(&descriptor());
        for (_, url) in super::ROLE_URLS {
            assert!(
                text.contains(&format!("/run/secrets/{url}")),
                "{url}: {text}"
            );
            assert!(text.contains(&format!("secrets/{url}")), "{url}: {text}");
        }
    }

    #[test]
    fn migrations_are_ordered_and_use_only_the_owner_url() {
        let text = migrate(&descriptor());
        let gateway = text.find("qr-gateway --migrate-only").expect("gateway");
        let data = text.find("qr-data --migrate-only").expect("data");
        let evidence = text.find("qr-evidence --migrate-only").expect("evidence");
        let simulation = text
            .find("qr-simulation --migrate-only")
            .expect("simulation");
        assert!(gateway < data && data < evidence && evidence < simulation);
        assert!(text.contains("QR_DATABASE_OWNER_URL_FILE"));
        assert!(!text.contains("QR_DATABASE_URL_FILE"));
        assert!(!text.contains("QR_DATABASE_URL="));
        assert!(text.contains("PGSSLMODE=verify-full"));
        assert!(text.contains("PGSSLROOTCERT"));
    }

    #[test]
    fn the_bootstrap_script_names_the_four_databases_and_no_value() {
        let text = db_bootstrap(&descriptor());
        for database in ["qr_gateway", "qr_catalog", "qr_evidence", "qr_simulation"] {
            assert!(text.contains(database), "{database}: {text}");
        }
        assert!(!text.contains("postgres://"));
        assert!(!text.contains("amqps://"));
    }

    #[test]
    fn the_stack_name_is_used_in_the_operator_output() {
        let mut value: serde_json::Value =
            serde_json::from_str(include_str!("../../../../deploy/v3/deploy.example.json"))
                .expect("example");
        value["name"] = serde_json::json!("quantrule-lab");
        let descriptor: Descriptor = serde_json::from_value(value).expect("descriptor");
        assert_eq!(super::super::stack_name(&descriptor), "quantrule-lab");
    }
}
