//! Generate the client label table from the model registry.

use std::fs;
use std::path::Path;
use std::process::ExitCode;

use serde_json::Value;

const CODE_MAPS: [(&str, &str); 11] = [
    ("EVENT_TYPES", "event_types"),
    ("LEVEL_SUBTYPES", "level_subtypes"),
    ("DIVERGENCE_SUBTYPES", "divergence_subtypes"),
    ("SIGNAL_SUBTYPES", "signal_subtypes"),
    ("SOURCES", "sources"),
    ("ROLES", "roles"),
    ("SCALES", "scales"),
    ("TARGET_BASES", "target_bases"),
    ("LIFECYCLES", "lifecycles"),
    ("STAGES", "stages"),
    ("UNAVAILABLE_REASONS", "unavailable_reasons"),
];

/// Run `qr-governance labels`.
///
/// Usage:
///
/// ```text
/// qr-governance labels generate [--write] [--root <path>]
/// ```
#[must_use]
pub fn run(args: &[String]) -> ExitCode {
    match execute(args) {
        Ok(code) => ExitCode::from(code),
        Err(error) => {
            eprintln!("error: {error}");
            ExitCode::FAILURE
        }
    }
}

fn execute(args: &[String]) -> Result<u8, String> {
    let Some(command) = args.first().map(String::as_str) else {
        return Err("labels needs generate".to_owned());
    };
    if command != "generate" {
        return Err(format!("unknown labels command {command}"));
    }
    let mut write = false;
    let mut root = Path::new(".").to_path_buf();
    let mut index = 1;
    while index < args.len() {
        match args[index].as_str() {
            "--write" => write = true,
            "--root" => {
                index += 1;
                root = Path::new(
                    args.get(index)
                        .ok_or_else(|| "--root needs a path".to_owned())?,
                )
                .to_path_buf();
            }
            other => return Err(format!("unknown argument {other}")),
        }
        index += 1;
    }
    let registry = load(&root.join("docs/registry/indicators.json"))?;
    let expected = render(&registry)?;
    let output = root.join("apps/web/src/lib/labels.generated.ts");
    if write {
        if let Some(parent) = output.parent() {
            fs::create_dir_all(parent)
                .map_err(|error| format!("cannot create {}: {error}", parent.display()))?;
        }
        fs::write(&output, expected)
            .map_err(|error| format!("cannot write {}: {error}", output.display()))?;
        println!("wrote apps/web/src/lib/labels.generated.ts");
        return Ok(0);
    }
    if !output.is_file() {
        eprintln!("error: apps/web/src/lib/labels.generated.ts is missing");
        return Ok(1);
    }
    let actual = fs::read_to_string(&output)
        .map_err(|error| format!("cannot read {}: {error}", output.display()))?;
    if actual == expected {
        println!("labels ok: the generated client table matches the registry");
        return Ok(0);
    }
    eprintln!(
        "error: apps/web/src/lib/labels.generated.ts is stale; run `qr-governance labels generate --write`"
    );
    if let Some(line) = expected
        .lines()
        .zip(actual.lines())
        .position(|(want, have)| want != have)
    {
        eprintln!("  first difference at line {}", line + 1);
        eprintln!(
            "  expected: {}",
            expected.lines().nth(line).unwrap_or_default()
        );
        eprintln!(
            "  found:    {}",
            actual.lines().nth(line).unwrap_or_default()
        );
    }
    Ok(1)
}

fn load(path: &Path) -> Result<Value, String> {
    let text = fs::read_to_string(path)
        .map_err(|error| format!("cannot read {}: {error}", path.display()))?;
    serde_json::from_str(&text).map_err(|error| format!("cannot parse {}: {error}", path.display()))
}

fn render(registry: &Value) -> Result<String, String> {
    let codes = registry
        .get("codes")
        .and_then(Value::as_object)
        .ok_or_else(|| "the registry has no codes object".to_owned())?;
    let events = registry
        .get("events")
        .and_then(Value::as_array)
        .ok_or_else(|| "the registry has no events array".to_owned())?;
    let indicators = registry
        .get("indicators")
        .and_then(Value::as_array)
        .ok_or_else(|| "the registry has no indicators array".to_owned())?;
    let mut blocks = vec![
        "// Generated by qr-governance labels generate from docs/registry/indicators.json."
            .to_owned(),
        "// Do not edit by hand; run `qr-governance labels generate --write`.".to_owned(),
        String::new(),
    ];
    for (name, key) in CODE_MAPS {
        let values = codes
            .get(key)
            .and_then(Value::as_object)
            .ok_or_else(|| format!("the registry has no {key} code map"))?;
        let mut labels = std::collections::BTreeMap::new();
        for (raw_code, label) in values {
            let code = raw_code
                .parse::<i64>()
                .map_err(|_| format!("{key} has a non-integer code {raw_code}"))?;
            let label = label
                .as_str()
                .ok_or_else(|| format!("{key} code {raw_code} has no label"))?;
            labels.insert(code, label.to_owned());
        }
        blocks.push(block(name, &labels));
        blocks.push(String::new());
    }
    blocks.push(block("EVENTS", &labelled(events, "id")?));
    blocks.push(String::new());
    blocks.push(block("INDICATORS", &labelled(indicators, "name")?));
    let mut text = blocks.join("\n");
    while text.ends_with('\n') {
        text.pop();
    }
    text.push('\n');
    Ok(text)
}

fn labelled(
    entries: &[Value],
    field: &str,
) -> Result<std::collections::BTreeMap<i64, String>, String> {
    let mut labels = std::collections::BTreeMap::new();
    for entry in entries {
        let code = entry
            .get("code")
            .and_then(Value::as_i64)
            .ok_or_else(|| format!("an entry has no integer code or {field}"))?;
        let label = entry
            .get(field)
            .and_then(Value::as_str)
            .ok_or_else(|| format!("an entry has no integer code or {field}"))?;
        if labels.insert(code, label.to_owned()).is_some() {
            return Err(format!("code {code} is assigned twice"));
        }
    }
    Ok(labels)
}

fn block(name: &str, labels: &std::collections::BTreeMap<i64, String>) -> String {
    let mut lines = vec![format!(
        "export const {name}: Readonly<Record<number, string>> = {{"
    )];
    for (code, label) in labels {
        lines.push(format!(
            "  {code}: {},",
            serde_json::to_string(label).unwrap_or_default()
        ));
    }
    lines.push("};".to_owned());
    lines.join("\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_block_is_sorted_by_code() {
        let mut labels = std::collections::BTreeMap::new();
        labels.insert(10, "ten".to_owned());
        labels.insert(2, "two".to_owned());
        assert_eq!(
            block("X", &labels),
            "export const X: Readonly<Record<number, string>> = {\n  2: \"two\",\n  10: \"ten\",\n};"
        );
    }
}
