#!/usr/bin/env python3
"""Generate the client label table from the model registry.

The Rust constants are the runtime identity; ``docs/registry/indicators.json``
is the registry metadata that ``check_registry.py`` keeps in step with them.
This generator reads the same JSON and emits one TypeScript table, so the client
has one mapping from every numeric code to a word. The gate fails when the
checked-in file drifts.

Usage:
    python3 tools/generate_labels.py
    python3 tools/generate_labels.py --write
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "docs/registry/indicators.json"
OUTPUT = ROOT / "apps/web/src/lib/labels.generated.ts"

CODE_MAPS = [
    ("EVENT_TYPES", "event_types"),
    ("LEVEL_SUBTYPES", "level_subtypes"),
    ("DIVERGENCE_SUBTYPES", "divergence_subtypes"),
    ("SIGNAL_SUBTYPES", "signal_subtypes"),
    ("SOURCES", "sources"),
    ("ROLES", "roles"),
    ("SCALES", "scales"),
    ("TARGET_BASES", "target_bases"),
    ("LIFECYCLES", "lifecycles"),
    ("STAGES", "stages"),
    ("UNAVAILABLE_REASONS", "unavailable_reasons"),
]


def load(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise SystemExit(f"error: cannot read {path}: {error}") from None


def labelled(entries: list[dict[str, Any]], field: str) -> dict[int, str]:
    labels: dict[int, str] = {}
    for entry in entries:
        code = entry.get("code")
        label = entry.get(field)
        if not isinstance(code, int) or not isinstance(label, str):
            raise SystemExit(f"error: an entry has no integer code or {field}")
        if code in labels:
            raise SystemExit(f"error: code {code} is assigned twice")
        labels[code] = label
    return labels


def block(name: str, labels: dict[int, str]) -> str:
    lines = [f"export const {name}: Readonly<Record<number, string>> = {{"]
    for code in sorted(labels):
        lines.append(f"  {code}: {json.dumps(labels[code], ensure_ascii=False)},")
    lines.append("};")
    return "\n".join(lines)


def render(registry: dict[str, Any]) -> str:
    codes = registry.get("codes")
    if not isinstance(codes, dict):
        raise SystemExit("error: the registry has no codes object")
    events = registry.get("events")
    indicators = registry.get("indicators")
    if not isinstance(events, list) or not isinstance(indicators, list):
        raise SystemExit("error: the registry has no events or indicators array")

    blocks = [
        "// Generated by tools/generate_labels.py from docs/registry/indicators.json.",
        "// Do not edit by hand; run `python3 tools/generate_labels.py --write`.",
        "",
    ]
    for name, key in CODE_MAPS:
        values = codes.get(key)
        if not isinstance(values, dict):
            raise SystemExit(f"error: the registry has no {key} code map")
        labels: dict[int, str] = {}
        for raw_code, label in values.items():
            try:
                code = int(raw_code)
            except (TypeError, ValueError):
                raise SystemExit(f"error: {key} has a non-integer code {raw_code}") from None
            if not isinstance(label, str):
                raise SystemExit(f"error: {key} code {raw_code} has no label")
            labels[code] = label
        blocks.append(block(name, labels))
        blocks.append("")
    blocks.append(block("EVENTS", labelled(events, "id")))
    blocks.append("")
    blocks.append(block("INDICATORS", labelled(indicators, "name")))
    return "\n".join(blocks).rstrip() + "\n"


def check() -> int:
    expected = render(load(REGISTRY))
    if not OUTPUT.is_file():
        print(f"error: {OUTPUT.relative_to(ROOT)} is missing", file=sys.stderr)
        return 1
    actual = OUTPUT.read_text(encoding="utf-8")
    if actual != expected:
        print(
            f"error: {OUTPUT.relative_to(ROOT)} is stale; "
            "run `python3 tools/generate_labels.py --write`",
            file=sys.stderr,
        )
        for line, (want, have) in enumerate(zip(expected.splitlines(), actual.splitlines()), 1):
            if want != have:
                print(f"  first difference at line {line}", file=sys.stderr)
                print(f"  expected: {want}", file=sys.stderr)
                print(f"  found:    {have}", file=sys.stderr)
                break
        return 1
    print("labels ok: the generated client table matches the registry")
    return 0


def write() -> int:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(load(REGISTRY)), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="rewrite the generated file")
    arguments = parser.parse_args()
    return write() if arguments.write else check()


if __name__ == "__main__":
    raise SystemExit(main())
