DEFAULT_READINGS = FIXTURES / "readings_golden.csv"
DEFAULT_PROGRESSION = FIXTURES / "progression_golden.csv"
DEFAULT_LEDGER = FIXTURES / "progression_legs_golden.csv"
DEFAULT_DASHBOARD = FIXTURES / "dashboard_readings_golden.csv"
DEFAULT_REPORT = FIXTURES / "market_report_golden.txt"

