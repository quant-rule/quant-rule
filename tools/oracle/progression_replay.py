#!/usr/bin/env python3
"""Check or regenerate the Progression golden fixtures.

The replay is independent of the Rust implementation: it reads the checked-in
readings fixture, runs the contract §8.4 state machine from
``progression_model.py``, and renders the per-bar Progression fixture and the
retained-leg ledger.

``--check`` (the default) compares the rendered files with the checked-in ones
and exits nonzero on any difference. ``--write`` rewrites them deliberately.
"""

from __future__ import annotations

import argparse
import csv
import difflib
from pathlib import Path
import sys
from typing import Optional

import progression_model as model

REPO_ROOT = Path(__file__).resolve().parents[2]
FIXTURES = REPO_ROOT / "crates" / "quantrule-model" / "tests" / "fixtures"

DEFAULT_READINGS = FIXTURES / "readings_golden.csv"
DEFAULT_PROGRESSION = FIXTURES / "progression_golden.csv"
DEFAULT_LEDGER = FIXTURES / "progression_legs_golden.csv"

READINGS_HEADER = (
    "bar,timestamp,open,high,low,close,volume,ema20,ema50,ema200,rsi14,atr14,"
    "rvol20,minor_candidate_high,minor_candidate_low,minor_pivot_high,"
    "minor_pivot_low,minor_pivot_occurred_at,major_candidate_high,"
    "major_candidate_low,major_pivot_high,major_pivot_low,"
    "major_pivot_occurred_at"
)

PROGRESSION_HEADER = (
    "bar,timestamp,open,high,low,close,volume,progress,stage_code,"
    "leg_direction,leg_scale_code,size_percentile,readiness_code,"
    "unavailable_reason_code,state_age_bars,state_changes_50,minor_leg_id,"
    "minor_timeframe_secs,minor_scale_code,minor_origin_price,"
    "minor_origin_occurred_at,minor_origin_available_at,"
    "minor_origin_confirmed_code,minor_direction_code,minor_target_price,"
    "minor_target_basis_code,minor_target_version,minor_target_stable_code,"
    "minor_progress,minor_displacement_price,minor_displacement_atr,"
    "minor_lifecycle_code,minor_stage_code,minor_target_reached_code,"
    "major_leg_id,major_timeframe_secs,major_scale_code,major_origin_price,"
    "major_origin_occurred_at,major_origin_available_at,"
    "major_origin_confirmed_code,major_direction_code,major_target_price,"
    "major_target_basis_code,major_target_version,major_target_stable_code,"
    "major_progress,major_displacement_price,major_displacement_atr,"
    "major_lifecycle_code,major_stage_code,major_target_reached_code"
)

LEDGER_HEADER = (
    "leg_id,timeframe_secs,scale_code,origin_price,origin_occurred_at,"
    "origin_available_at,origin_confirmed_code,direction_code,target_price,"
    "target_basis_code,target_version,target_stable_code,progress,"
    "displacement_price,displacement_atr,lifecycle_code,stage_code,"
    "target_reached_code"
)

PROGRESSION_COMMENTS = (
    "# Golden fixture for the published Progression values.",
    "#",
    "# Generated by tools/oracle/progression_replay.py (#197) from the checked-in",
    "# readings_golden.csv. The replay implements contract §8.4 and §9 and does",
    "# not call or import the Rust implementation. Run the script with --check to",
    "# verify this file, or with --write to regenerate it deliberately.",
)


def format_float(value: Optional[float]) -> str:
    """The checked-in CSV uses Python's shortest round-trip float text."""
    return "" if value is None else str(value)


def format_published_float(value: Optional[float]) -> str:
    """The published CSV columns drop the ``.0`` of an integral float.

    The fixture's published ``progress`` and ``size_percentile`` columns were
    rendered by the original replay's ``str(int(value))`` branch, while the
    per-leg columns kept ``str(float(value))``. Preserving that distinction
    keeps the checked-in bytes unchanged without weakening the comparison.
    """
    if value is None:
        return ""
    text = str(value)
    return text[:-2] if text.endswith(".0") else text


def format_int(value: Optional[int]) -> str:
    """An absent integer is an empty CSV cell, never a zero."""
    return "" if value is None else str(value)


def optional_float(field: str) -> Optional[float]:
    return None if field == "" else float(field)


def optional_int(field: str) -> Optional[int]:
    return None if field == "" else int(field)


def leg_fields(leg: Optional[model.LegRecord]) -> list[str]:
    """The 18 CSV fields of one leg record, or 18 empty cells."""
    if leg is None:
        return [""] * 18
    return [
        str(leg.leg_id),
        format_int(leg.timeframe_secs),
        str(leg.scale_code),
        format_float(leg.origin_price),
        str(leg.origin_occurred_at),
        format_int(leg.origin_available_at),
        str(leg.origin_confirmed_code),
        str(leg.direction_code),
        format_float(leg.target_price),
        format_int(leg.target_basis_code),
        str(leg.target_version),
        str(leg.target_stable_code),
        format_float(leg.progress),
        format_float(leg.displacement_price),
        format_float(leg.displacement_atr),
        str(leg.lifecycle_code),
        format_int(leg.stage_code),
        format_int(leg.target_reached_code),
    ]


def read_readings(
    path: Path,
) -> tuple[
    list[model.Candle],
    dict[int, list[Optional[model.Pivot]]],
    dict[int, list[Optional[model.Pivot]]],
    list[Optional[float]],
]:
    """Parses the checked-in readings fixture.

    The readings fixture is the independently generated input: candles, ATR 14,
    pivot candidates, and confirmed pivots at both scales. This function does
    not recompute any reading.
    """
    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames is None:
            raise ValueError(f"{path} has no header")
        if ",".join(reader.fieldnames) != READINGS_HEADER:
            raise ValueError(f"{path} does not have the expected header")

        candles: list[model.Candle] = []
        candidates = {model.MINOR: [], model.MAJOR: []}
        confirmed = {model.MINOR: [], model.MAJOR: []}
        atr14: list[Optional[float]] = []

        for row in reader:
            bar = int(row["bar"])
            if bar != len(candles):
                raise ValueError(f"{path}: bars must be contiguous at {bar}")
            candles.append(
                model.Candle(
                    bar=bar,
                    timestamp=int(row["timestamp"]),
                    open=float(row["open"]),
                    high=float(row["high"]),
                    low=float(row["low"]),
                    close=float(row["close"]),
                    volume=optional_float(row["volume"]),
                )
            )
            atr14.append(optional_float(row["atr14"]))

            for scale, prefix in (
                (model.MINOR, "minor"),
                (model.MAJOR, "major"),
            ):
                high = optional_float(row[f"{prefix}_candidate_high"])
                low = optional_float(row[f"{prefix}_candidate_low"])
                if high is not None and low is not None:
                    raise ValueError(
                        f"{path}: bar {bar} has both {prefix} candidates"
                    )
                if high is not None:
                    candidates[scale].append(
                        model.Pivot(scale, "high", high, bar, bar)
                    )
                elif low is not None:
                    candidates[scale].append(
                        model.Pivot(scale, "low", low, bar, bar)
                    )
                else:
                    candidates[scale].append(None)

                pivot_high = optional_float(row[f"{prefix}_pivot_high"])
                pivot_low = optional_float(row[f"{prefix}_pivot_low"])
                occurred = optional_int(row[f"{prefix}_pivot_occurred_at"])
                if pivot_high is not None and pivot_low is not None:
                    raise ValueError(
                        f"{path}: bar {bar} has both {prefix} pivots"
                    )
                if pivot_high is not None:
                    if occurred is None:
                        raise ValueError(
                            f"{path}: bar {bar} has a {prefix} high without "
                            "an occurrence bar"
                        )
                    confirmed[scale].append(
                        model.Pivot(scale, "high", pivot_high, occurred, bar)
                    )
                elif pivot_low is not None:
                    if occurred is None:
                        raise ValueError(
                            f"{path}: bar {bar} has a {prefix} low without "
                            "an occurrence bar"
                        )
                    confirmed[scale].append(
                        model.Pivot(scale, "low", pivot_low, occurred, bar)
                    )
                else:
                    if occurred is not None:
                        raise ValueError(
                            f"{path}: bar {bar} has a {prefix} occurrence "
                            "without a pivot"
                        )
                    confirmed[scale].append(None)

    return candles, candidates, confirmed, atr14


def render_progression(
    candles: list[model.Candle], bars: tuple[model.Bar, ...]
) -> str:
    """Renders the per-bar Progression fixture."""
    lines = list(PROGRESSION_COMMENTS)
    lines.append(PROGRESSION_HEADER)
    for candle, bar in zip(candles, bars):
        fields = [
            str(candle.bar),
            str(candle.timestamp),
            format_float(candle.open),
            format_float(candle.high),
            format_float(candle.low),
            format_float(candle.close),
            format_float(candle.volume),
            format_published_float(bar.progress),
            format_int(bar.stage_code),
            format_int(bar.leg_direction),
            format_int(bar.leg_scale_code),
            format_published_float(bar.size_percentile),
            str(bar.readiness_code),
            format_int(bar.unavailable_reason_code),
            str(bar.state_age_bars),
            str(bar.state_changes_50),
        ]
        fields.extend(leg_fields(bar.minor_leg))
        fields.extend(leg_fields(bar.major_leg))
        lines.append(",".join(fields))
    return "\n".join(lines) + "\n"


def render_ledger(legs: tuple[model.LegRecord, ...]) -> str:
    """Renders the retained-leg ledger fixture.

    The ledger carries no comment header, so the file stays byte-identical to
    its pre-#197 form and the Rust loader's header handling is untouched.
    """
    lines = [LEDGER_HEADER]
    for leg in legs:
        lines.append(",".join(leg_fields(leg)))
    return "\n".join(lines) + "\n"


def compare(name: str, path: Path, rendered: str) -> bool:
    """Compares one rendered file with its checked-in counterpart."""
    existing = path.read_text(encoding="utf-8")
    if existing == rendered:
        print(f"OK {name}: {path}")
        return True

    print(f"MISMATCH {name}: {path}", file=sys.stderr)
    diff = difflib.unified_diff(
        existing.splitlines(keepends=True),
        rendered.splitlines(keepends=True),
        fromfile=str(path),
        tofile=f"{path} (replay)",
        n=2,
    )
    sys.stderr.writelines(diff)
    return False


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Check or regenerate the Progression goldens from the checked-in "
            "readings fixture."
        )
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="compare the checked-in fixtures with the replay (default)",
    )
    parser.add_argument(
        "--write",
        action="store_true",
        help="rewrite the fixtures from the replay",
    )
    parser.add_argument(
        "--readings",
        type=Path,
        default=DEFAULT_READINGS,
        help=f"readings fixture (default: {DEFAULT_READINGS})",
    )
    parser.add_argument(
        "--progression",
        type=Path,
        default=DEFAULT_PROGRESSION,
        help=f"per-bar fixture (default: {DEFAULT_PROGRESSION})",
    )
    parser.add_argument(
        "--ledger",
        type=Path,
        default=DEFAULT_LEDGER,
        help=f"ledger fixture (default: {DEFAULT_LEDGER})",
    )
    args = parser.parse_args(argv)

    if args.check and args.write:
        parser.error("choose --check or --write, not both")
    write = args.write

    candles, candidates, confirmed, atr14 = read_readings(args.readings)
    result = model.replay(candles, candidates, confirmed, atr14)

    rendered = {
        "progression": (
            args.progression,
            render_progression(candles, result.bars),
        ),
        "ledger": (args.ledger, render_ledger(result.legs)),
    }

    if write:
        for name, (path, text) in rendered.items():
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {name}: {path}")
        return 0

    ok = True
    for name, (path, text) in rendered.items():
        ok = compare(name, path, text) and ok
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
