#!/usr/bin/env python3
"""Check or regenerate the Progression golden fixtures.

The replay is independent of the Rust implementation: it reads the checked-in
readings fixture, runs the contract §8.4 state machine from
``progression_model.py``, and renders the Progression files and the
Progression-derived parts of the dashboard and market-report fixtures.

``--check`` (the default) compares the rendered files with the checked-in ones
and exits nonzero on any difference. ``--write`` rewrites them deliberately.
The non-Progression dashboard rows and report lines are preserved byte for
byte from the existing files; those parts come from their own earlier
independent replays.
"""

from __future__ import annotations

import argparse
import csv
import difflib
from pathlib import Path
import re
import sys
from typing import Optional

import progression_model as model

REPO_ROOT = Path(__file__).resolve().parents[2]
