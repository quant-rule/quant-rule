#!/usr/bin/env python3
"""Fail when the product carries Python.

The product is the Rust workspace under ``crates/``, the clients under
``apps/``, the image directory under ``docker/``, and the ``Dockerfile``. A
``.py`` file in that tree, or an interpreter reference in a file that ships or
builds the image, would put Python back into the product.

The repository's own governance scripts stay under ``tools/`` and ``docs/``
keeps the historical records that cite them, so neither tree is scanned. Every
other authored ``.py`` file fails; the local ``data/`` root and generated build
output are not authored product files and are skipped.

The checker is the source-tree half of the gate. The built filesystem is the
other half: ``docker/check-no-python.sh`` runs in the Dockerfile final stage and
against the release image.
"""

from __future__ import annotations

import os
import re
import sys
from collections.abc import Iterator
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# The product tree. A .py file here is a product file, not a governance script.
PRODUCT_ROOTS = ("crates", "apps", "docker")
PRODUCT_FILES = ("Dockerfile",)

# Governance Python lives here; historical records live under docs/.
ALLOWED_PY_PREFIXES = ("tools/", "docs/")

# Build output and vendored trees are generated, not authored product files.
SKIP_ANYWHERE = {
    "node_modules",
    "target",
    "__pycache__",
    ".venv",
    "venv",
    "dist",
    "test-results",
    "playwright-report",
    "blob-report",
}
# The repository root also holds Git internals and the local data store.
SKIP_ROOT = {".git", "data"}

MAX_BYTES = 2 * 1024 * 1024

# An interpreter reference is the executable form: ``python`` or ``python3``
# followed by nothing, an argument, or a version suffix. The lookbehind keeps
# ``quantrule-server:python-gate`` and ``check-no-python.sh`` out, the lookahead
# keeps ``python_number`` out, and the match is case-sensitive so prose about
# "Python" in a comment is not a command reference.
INTERPRETER_PATTERN = re.compile(
    r"(?<![\w./-])(python3?)(?:\.\d+)?(?![A-Za-z0-9_])"
)

# These files name the interpreter on purpose:
# - docker/README.md documents the image checks;
# - docker/check-no-python.sh implements the image assertion and must name the
#   interpreter it rejects;
# - apps/web/src/lib/labels.generated.ts is generated by tools/generate_labels.py
#   and carries the command that regenerates it, in a comment, not a call.
REFERENCE_ALLOWLIST = {
    "docker/README.md",
    "docker/check-no-python.sh",
    "apps/web/src/lib/labels.generated.ts",
}


def _walk(root: Path, top: Path) -> Iterator[Path]:
    """Yield every authored file under ``top`` with the build trees pruned."""
    if not top.is_dir():
        return
    for directory, names, files in os.walk(top):
        current = Path(directory)
        names[:] = sorted(
            name for name in names if name not in SKIP_ANYWHERE
        )
        for name in sorted(files):
            yield current / name


def python_files(root: Path) -> list[str]:
    """Every .py file outside the governance and history trees, sorted."""
    found: list[str] = []
    for directory, names, files in os.walk(root):
        current = Path(directory)
        relative = current.relative_to(root)
        names[:] = sorted(
            name
            for name in names
            if name not in SKIP_ANYWHERE
            and not (relative == Path(".") and name in SKIP_ROOT)
        )
        for name in sorted(files):
            if name.endswith(".py"):
                found.append((relative / name).as_posix())
    allowed = tuple(ALLOWED_PY_PREFIXES)
    return sorted({name for name in found if not name.startswith(allowed)})


def product_files(root: Path) -> list[Path]:
    """Every file the product builds or ships, in a deterministic order."""
    found: list[Path] = []
    for top in PRODUCT_ROOTS:
        found.extend(_walk(root, root / top))
    for name in PRODUCT_FILES:
        path = root / name
        if path.is_file():
            found.append(path)
    return sorted(found)


def reference_errors(path: Path, name: str) -> list[str]:
    """Report one line per interpreter reference in an authored product file."""
    try:
        if path.stat().st_size > MAX_BYTES:
            return []
        data = path.read_bytes()
    except OSError:
        return []
    if b"\x00" in data[:4096]:
        return []
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return []
    errors: list[str] = []
    for number, line in enumerate(text.splitlines(), 1):
        match = INTERPRETER_PATTERN.search(line)
        if match is not None:
            errors.append(
                f"{name}:{number}: Python interpreter reference {match.group(0)!r}"
            )
    return errors


def check(root: Path) -> list[str]:
    """Return every Python gate violation under ``root``; empty means pass."""
    errors = [
        f"{name}: Python file in the product tree"
        for name in python_files(root)
    ]
    for path in product_files(root):
        name = path.relative_to(root).as_posix()
        if name in REFERENCE_ALLOWLIST:
            continue
        errors.extend(reference_errors(path, name))
    return errors


def main() -> int:
    errors = check(ROOT)
    if errors:
        for error in errors:
            print(f"error: {error}", file=sys.stderr)
        return 1
    print(
        "python gate ok: no authored .py file outside tools/ and docs/, "
        f"{len(product_files(ROOT))} product files carry no interpreter reference"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
